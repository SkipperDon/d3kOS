#!/usr/bin/env python3
"""
generate_manifest.py
Regenerates mobile/file-manifest.php from local source files.
Run after every Pi service deploy to keep hashes in sync.

Usage:
    python3 deployment/scripts/generate_manifest.py

Output:
    Overwrites atmyboat-forum/wp-content/themes/twentytwenty-child/mobile/file-manifest.php
"""

import hashlib
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

# ── File map: Pi path → local repo path ──────────────────────────────────────
# Key   = path on Pi (/opt/d3kos/...)
# Value = path relative to Helm-OS repo root

REPO_ROOT  = Path(__file__).resolve().parent.parent.parent   # Helm-OS/
FORUM_ROOT = REPO_ROOT.parent / 'atmyboat-forum'

FILE_MAP = {
    '/opt/d3kos/services/cloud-agent/cloud_agent.py':
        REPO_ROOT / 'deployment/v0.9.4/pi_source/cloud_agent.py',

    '/opt/d3kos/services/cloud-agent/fix_my_pi.py':
        REPO_ROOT / 'deployment/v0.9.4/pi_source/fix_my_pi.py',

    '/opt/d3kos/services/cloud-agent/ota_upgrade.py':
        REPO_ROOT / 'deployment/v0.9.4/pi_source/ota_upgrade.py',

    '/opt/d3kos/services/alert_watcher.py':
        REPO_ROOT / 'deployment/v0.9.4/pi_source/alert_watcher.py',

    '/opt/d3kos/services/os_lockdown.py':
        REPO_ROOT / 'deployment/v0.9.4/pi_source/os_lockdown.py',

    '/opt/d3kos/services/tier/tier_service.py':
        REPO_ROOT / 'deployment/v0.9.4/pi_source/tier_service.py',

    '/opt/d3kos/services/dashboard/app.py':
        REPO_ROOT / 'deployment/d3kOS/dashboard/app.py',

    '/opt/d3kos/services/export/export_worker.py':
        REPO_ROOT / 'deployment/v0.9.4/pi_source/export_worker.py',

    '/opt/d3kos/services/export/export_categories.py':
        REPO_ROOT / 'deployment/v0.9.4/pi_source/export_categories.py',

    '/opt/d3kos/services/live/live_session.py':
        REPO_ROOT / 'deployment/v0.9.4/pi_source/live_session.py',

    '/opt/d3kos/services/marine-vision/camera_stream_manager.py':
        REPO_ROOT / 'deployment/v0.9.4/pi_source/camera_stream_manager.py',
}

VERSION = '0.9.4'
OUTPUT  = FORUM_ROOT / 'wp-content/themes/twentytwenty-child/mobile/file-manifest.php'


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(65536), b''):
            h.update(chunk)
    return h.hexdigest()


def main():
    errors = []
    entries = {}

    for pi_path, local_path in FILE_MAP.items():
        if not local_path.exists():
            errors.append(f'  MISSING: {local_path}')
            continue
        size   = local_path.stat().st_size
        digest = sha256(local_path)
        entries[pi_path] = {'sha256': digest, 'size': size}
        print(f'  ✓ {pi_path.split("/")[-1]:40s} {digest[:16]}... {size:>8d} bytes')

    if errors:
        print('\nERRORS — these files were not found locally:')
        for e in errors:
            print(e)
        print('\nManifest NOT updated. Fix missing files and re-run.')
        sys.exit(1)

    generated = datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')

    # Build PHP entries
    php_entries = ''
    for pi_path, info in entries.items():
        php_entries += f"""        '{pi_path}' => [
            'sha256' => '{info['sha256']}',
            'size'   => {info['size']},
        ],\n"""

    php = f"""<?php
/**
 * mobile/file-manifest.php
 * Serves the SHA-256 manifest of core d3kOS service files.
 * Pi calls this during Fix My Pi to verify file integrity.
 *
 * Method: GET
 * Auth:   Bearer API key (amboat_auth_pi_request)
 *
 * AUTO-GENERATED by deployment/scripts/generate_manifest.py
 * Do not edit manually — run the generator after every Pi service deploy.
 */

require_once __DIR__ . '/config.php';
require_once __DIR__ . '/auth.php';

header( 'Access-Control-Allow-Origin: *' );
header( 'Access-Control-Allow-Headers: Authorization, X-Device-Token, Content-Type' );
header( 'Access-Control-Allow-Methods: GET, OPTIONS' );

if ( ${'_SERVER'}['REQUEST_METHOD'] === 'OPTIONS' ) {{
    http_response_code( 204 );
    exit;
}}

if ( ${'_SERVER'}['REQUEST_METHOD'] !== 'GET' ) {{
    amboat_send_error( 'Method not allowed.', 405 );
}}

// Pi-facing auth — API key + X-Device-Token
amboat_auth_pi_request();

$manifest = [
    'version'   => '{VERSION}',
    'generated' => '{generated}',
    'files'     => [
{php_entries}    ],
];

amboat_send_success( $manifest );
"""

    OUTPUT.write_text(php)
    print(f'\n✓ file-manifest.php updated — {len(entries)} files, generated {generated}')
    print(f'  → {OUTPUT}')


if __name__ == '__main__':
    print(f'Generating manifest from local source files...')
    main()
