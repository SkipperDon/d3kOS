def test_ssh_keygen_called_when_keys_missing():
    """first-boot-setup.sh calls ssh-keygen -A when host keys are absent."""
    content = FIRST_BOOT.read_text()
    assert "ssh-keygen -A" in content, "ssh-keygen -A not found in first-boot-setup.sh"
    # Guard condition ensures it only runs when keys are missing
    assert "ssh_host_*_key" in content, "Guard condition for missing keys not found"


def test_ssh_keygen_skipped_when_keys_present():
    """Guard condition prevents ssh-keygen -A from running when keys exist."""
    content = FIRST_BOOT.read_text()
    # The 'if ! ls' guard makes ssh-keygen conditional on keys being absent
    assert "if ! ls /etc/ssh/ssh_host_*_key" in content, \
        "Guard 'if ! ls /etc/ssh/ssh_host_*_key' not found — keys will always be regenerated"


