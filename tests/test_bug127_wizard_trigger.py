def test_sanitize_removes_vessel_env_file(tmp_path):
    """Running the vessel.env removal snippet actually deletes the file."""
    # Create a fake vessel.env in tmpdir
    vessel_env = tmp_path / "vessel.env"
    vessel_env.write_text("VESSEL_NAME=TestBoat\n")
    assert vessel_env.exists()

    # Run just the relevant bash snippet (substituting tmpdir for /opt/d3kos/config)
    snippet = f"""
if [ -f "{vessel_env}" ]; then
    rm -f "{vessel_env}"
fi
"""
    result = subprocess.run(["bash", "-c", snippet], capture_output=True, text=True)
    assert result.returncode == 0, f"Bash snippet failed: {result.stderr}"
    assert not vessel_env.exists(), "vessel.env was not removed by the cleanup snippet"


